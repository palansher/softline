import asyncio  # Импорт библиотеки для асинхронного программирования (Event Loop, задачи, sleep)
import time  # Импорт библиотеки для работы с реальным временем (для логов)


# [ОПРЕДЕЛЕНИЕ КОРОУТИНЫ]
# Код внутри функции НЕ выполняется при объявлении.
# 'async def' создаёт асинхронную функцию (корутину).
async def task1(name, delay):
    # [СИНХРОННОЕ ВЫПОЛНЕНИЕ]
    # Печатаем текст. time.localtime() выполняет быстрый синхронный запрос времени.
    print(f"{name} началась в {time.strftime('%H:%M:%S', time.localtime())}")

    # [ТОЧКА ПРИОСТАНОВКИ / ПЕРЕДАЧА УПРАВЛЕНИЯ]
    # 'await' говорит Event Loop: «Я засыпаю на 'delay' секунд. Забери у меня управление
    # и делай другие задачи, пока я жду!». Это НЕ блокирует поток программы.
    await asyncio.sleep(delay)

    # [СИНХРОННОЕ ВЫПОЛНЕНИЕ]
    # Когда время паузы истекло и Event Loop вернулся сюда, выполняем печать завершения.
    print(f"{name} завершилась в {time.strftime('%H:%M:%S', time.localtime())}")

    # [ВОЗВРАТ ЗНАЧЕНИЯ]
    # Возвращаем строковый результат. В асинхронном коде он попадет в объект Task.
    return f"Результат {name}"


# [ОПРЕДЕЛЕНИЕ КОРОУТИНЫ]
# (Примечание: эта функция объявлена, но ниже в вашем коде main() она не вызывается)
async def task2(name, delay):
    print(f"{name} началась в {time.strftime('%H:%M:%S', time.localtime())}")
    await asyncio.sleep(delay)
    print(f"{name} завершилась в {time.strftime('%H:%M:%S', time.localtime())}")
    return f"Результат {name}"


# [ОПРЕДЕЛЕНИЕ ГЛАВНОЙ КОРОУТИНЫ]
async def main():
    # [СИНХРОННОЕ ВЫПОЛНЕНИЕ]Выводим время старта функции main
    print(f"Начало программы в {time.strftime('%H:%M:%S', time.localtime())}")

    # [РЕГИСТРАЦИЯ ЗАДАЧИ В EVENT LOOP + ПРИСВАИВАНИЕ]
    # asyncio.create_task() НЕ останавливает выполнение main().
    # Она заворачивает task1 в Task и мгновенно регистрирует её в Event Loop для фонового запуска.
    # В 'task_1' просто сохраняется ссылка на объект этой фоновой задачи.
    task_1 = asyncio.create_task(task1(name="Задача №1", delay=3))

    # [РЕГИСТРАЦИЯ ЗАДАЧИ В EVENT LOOP + ПРИСВАИВАНИЕ]
    # Вторая задача также мгновенно регистрируется в Event Loop.
    # Обе задачи (№1 и №2) теперь выполняются Event Loop'ом «параллельно» в фоновом режиме!
    task_2 = asyncio.create_task(task1(name="Задача №2", delay=2))  # Передаем task1

    # [ОЖИДАНИЕ + ПРИСВАИВАНИЕ РЕЗУЛЬТАТА]
    # 'await task_1' ПРИОСТАНАВЛИВАЕТ выполнение функции main().
    # main() ждет 3 секунды, пока Задача №1 полностью не завершится.
    # ПОКА main() ЖДЕТ, Задача №2 (которой нужно всего 2 сек) успевает завершиться на заднем фоне!
    result1 = await task_1

    # [СИНХРОННОЕ ВЫПОЛНЕНИЕ] Печатаем результат первой задачи (через ~3 секунды после старта)
    print("Получен результат:", result1)

    # [МГНОВЕННОЕ ПОЛУЧЕНИЕ РЕЗУЛЬТАТА + ПРИСВАИВАНИЕ]
    # Так как Задача №2 длилась 2 секунды, а мы уже прождали 3 секунды на первом await,
    # Задача №2 К ЭТОМУ МОМЕНТУ УЖЕ ЗАВЕРШЕНА.
    # Поэтому 'await task_2' НЕ ждет ни секунды, а сразу отдает готовый результат.
    result2 = await task_2

    # [СИНХРОННОЕ ВЫПОЛНЕНИЕ] Печатаем результат второй задачи
    print("Получен результат:", result2)


# [ТОЧКА ВХОДА В ПРОГРАММУ / СТАРТ EVENT LOOP]
# 1. Создает главный событийный цикл (Event Loop).
# 2. Запускает корутину main() внутри этого цикла.
# 3. Блокирует главный поток Python до полного завершения main().
# 4. Закрывает Event Loop по завершении.
asyncio.run(main())
